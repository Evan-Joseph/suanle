export const HEXAGRAMS: HexagramInfo[] = RAW.map((r, i) => ({
  n: i + 1,
  name: r[0],
  full: r[1],
  judgment: r[2],
  image: r[3],
  modern: r[4],
  letgo: r[5],
  tone: r[6],
  symbol: String.fromCodePoint(0x4dc0 + i),
}));

// Trigram order: 乾 震 坎 艮 坤 巽 离 兑
const TRIGRAM_BITS: Record<string, number> = {
  "111": 0, "100": 1, "010": 2, "001": 3, "000": 4, "011": 5, "101": 6, "110": 7,
};
export const TRIGRAM_NAMES = ["乾", "震", "坎", "艮", "坤", "巽", "离", "兑"];
export const TRIGRAM_IMAGES = ["天", "雷", "水", "山", "地", "风", "火", "泽"];

// KING_WEN[upper][lower]
const KING_WEN = [
  [1, 25, 6, 33, 12, 44, 13, 10],
  [34, 51, 40, 62, 16, 32, 55, 54],
  [5, 3, 29, 39, 8, 48, 63, 60],
  [26, 27, 4, 52, 23, 18, 22, 41],
  [11, 24, 7, 15, 2, 46, 36, 19],
  [9, 42, 59, 53, 20, 57, 37, 61],
  [14, 21, 64, 56, 35, 50, 30, 38],
  [43, 17, 47, 31, 45, 28, 49, 58],
];

export function hexFromBits(bits: number[]): HexagramInfo {
  const lower = TRIGRAM_BITS[bits.slice(0, 3).join("")];
  const upper = TRIGRAM_BITS[bits.slice(3, 6).join("")];
  return HEXAGRAMS[KING_WEN[upper][lower] - 1];
}

export function trigramsOf(bits: number[]) {
  const lower = TRIGRAM_BITS[bits.slice(0, 3).join("")];
  const upper = TRIGRAM_BITS[bits.slice(3, 6).join("")];
  return { upper: TRIGRAM_NAMES[upper] + TRIGRAM_IMAGES[upper], lower: TRIGRAM_NAMES[lower] + TRIGRAM_IMAGES[lower] };
}

export const isYang = (v: LineValue) => v === 7 || v === 9;

/** 三枚铜钱：背=3，字=2 */
export function tossCoins(rand: () => number = Math.random): { coins: (2 | 3)[]; value: LineValue } {
  const coins = [0, 1, 2].map(() => (rand() < 0.5 ? 2 : 3)) as (2 | 3)[];
  const value = (coins[0] + coins[1] + coins[2]) as LineValue;
  return { coins, value };
}

export function resolveCast(lines: LineValue[], question?: string): CastResult {
  const bits = lines.map((v) => (isYang(v) ? 1 : 0));
  const changing = lines.map((v, i) => (v === 6 || v === 9 ? i + 1 : 0)).filter(Boolean);
  const resultBits = lines.map((v, i) => (v === 6 ? 1 : v === 9 ? 0 : bits[i]));
  const nuclearBits = [bits[1], bits[2], bits[3], bits[2], bits[3], bits[4]];
  return {
    lines,
    original: hexFromBits(bits),
    nuclear: hexFromBits(nuclearBits),
    resulting: changing.length ? hexFromBits(resultBits) : null,
    changing,
    question,
    at: new Date().toISOString(),
  };
}

export const LINE_NAMES = (lines: LineValue[]) =>
  lines.map((v, i) => {
    const pos = ["初", "二", "三", "四", "五", "上"][i];
    const yy = isYang(v) ? "九" : "六";
    return i === 0 || i === 5 ? `${pos}${yy}` : `${yy}${pos}`;
  });

