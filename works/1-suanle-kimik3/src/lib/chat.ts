const TOPIC_RULES: [Topic, RegExp][] = [
  ["love", /恋|爱|对象|男朋|女朋|分手|复合|暗恋|追|crush|喜欢他|喜欢她|暧昧|结婚|相亲|老公|老婆|夫妻/],
  ["money", /钱|穷|工资|薪水|副业|理财|存款|买房|贷|账单|消费/],
  ["work", /工作|班|加班|辞职|离职|老板|领导|同事|KPI|职场|裁员|求职|面试|事业/],
  ["family", /爸妈|父母|父亲|母亲|家人|孩子|催婚|催生|家里/],
  ["future", /未来|迷茫|方向|意义|人生|选择|以后|梦想/],
  ["self", /内耗|自己|自卑|自信|不够好|讨厌|敏感|性格/],
  ["anxiety", /焦虑|失眠|睡不着|慌|压力|崩溃|emo|抑郁|烦|心累|撑不住/],
];

export function routeTopic(text: string): Topic {
  for (const [topic, re] of TOPIC_RULES) if (re.test(text)) return topic;
  return "general";
}

export function buildReply(personaId: string, userText: string, turn: number): string {
  const persona = CORPUS[personaId] ?? CORPUS.laozhou;
  const topic = routeTopic(userText);
  const pool = persona[topic].length ? persona[topic] : persona.general;
  const rng = mulberry32(hashSeed(`${personaId}:${userText}:${turn}`));
  return pool[Math.floor(rng() * pool.length)];
}
