export const DEFAULT_PERSONA = PERSONAS[0];

export function personaById(id: string | undefined | null): Persona {
  return PERSONAS.find((p) => p.id === id) ?? DEFAULT_PERSONA;
}

/** 根据主题自动推荐一位大师（用于邀请语） */
export function routePersonaHint(text: string): Persona | null {
  const rules: Array<[RegExp, string]> = [
    [/塔罗|牌|桃花|复合|前任|暧昧|恋爱|分手|暗恋/, "selena"],
    [/八字|五行|生辰|缺什么|流年|运势/, "xuanji"],
    [/offer|辞职|裸辞|跳槽|概率|数据|投资/, "zero"],
    [/领导|同事|加薪|升职|小人|办公室|内斗/, "guiguzi"],
    [/意义|迷茫|焦虑|空|活着|人生|三十岁/, "linfeng"],
  ];
  for (const [re, id] of rules) if (re.test(text)) return personaById(id);
  return null;
}
