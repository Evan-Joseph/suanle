export interface OfflineReply {
  thinking: string;
  content: string;
}

export function offlineReply(userText: string, personaId: string): OfflineReply {
  const scenario = detect(userText);
  const persona = personaById(personaId);
  const bodies = BODIES[scenario];
  const body = bodies[Math.floor(Math.random() * bodies.length)];
  return {
    thinking: THINKS[scenario],
    content: `*${persona.name}抬眼看了看你*\n\n${body}\n\n——${SUALNLE_CLOSERS[Math.floor(Math.random() * SUALNLE_CLOSERS.length)]}`,
  };
}

/** 供标题接口使用的本地兜底 */
export function localTitle(text: string): string {
  const t = text.replace(/\s+/g, " ").trim();
  if (!t) return "一段没起名的心事";
  const scenario = detect(t);
  const map: Record<Scenario, string> = {
    career: "关于饭碗的心事",
    love: "一段感情的念头",
    money: "钱与安全感",
    mood: "深夜里的一点情绪",
    study: "上岸这件大事",
    general: "说说而已，说完就轻了",
  };
  return t.length <= 10 ? `「${t.slice(0, 10)}」` : map[scenario];
}
